"""
01_prepare_cohort.py
Cohort filtering, automatic CDC survey-design merging (WTSAFPRP, SDMVSTRA, SDMVPSU),
leakage-free stratified 70/30 partitioning, and training-only Z-score scaling
for the NHANES 2017–March 2020 cardiometabolic phenotyping study.
"""

from pathlib import Path
import json
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

# ------------------------------------------------------------------------------
# Configuration & Constants
# ------------------------------------------------------------------------------
RANDOM_SEED = 42
TEST_SIZE = 0.30

DATA_DIR = Path("data")
RAW_CSV_PATH = DATA_DIR / "Nhanes_Phenotype_Analytical_Matrix.csv"
SURVEY_CACHE_PATH = DATA_DIR / "nhanes_survey_weights_cache.parquet"
ARTIFACTS_DIR = Path("artifacts") / "prepared"

CDC_P_DEMO_URL = (
    "https://wwwn.cdc.gov/Nchs/Data/Nhanes/Public/2017/DataFiles/P_DEMO.xpt"
)
CDC_P_TRIGLY_URL = (
    "https://wwwn.cdc.gov/Nchs/Data/Nhanes/Public/2017/DataFiles/P_TRIGLY.xpt"
)

BIOMARKERS = [
    "HbA1c_Percent",
    "Triglycerides",
    "Total_Cholesterol",
    "HDL_Cholesterol",
    "BMI",
    "Systolic_BP",
]

SOCIODEMOGRAPHICS = [
    "Gender",
    "Race_Ethnicity",
    "Education_Level",
    "Income_Poverty_Ratio",
]

SECONDARY_CLINICAL = [
    "eGFR",
    "Inflammation_CRP",
    "Diastolic_BP",
    "LDL_Cholesterol",
]

SURVEY_DESIGN_COLS = [
    "WTSAFPRP",
    "SDMVSTRA",
    "SDMVPSU",
]


def load_survey_design_weights(cache_path: Path) -> pd.DataFrame:
    """
    Retrieve WTSAFPRP (fasting subsample weight), SDMVSTRA (stratum), and SDMVPSU (PSU)
    directly from CDC 2017-March 2020 XPT files and cache locally for reproducibility.
    """
    if cache_path.exists():
        print(f"Loading cached NHANES survey design weights from {cache_path}...")
        return pd.read_parquet(cache_path)

    print("Fetching NHANES 2017-March 2020 survey design variables from CDC...")
    demo = pd.read_sas(CDC_P_DEMO_URL, format="xport")[["SEQN", "SDMVSTRA", "SDMVPSU"]]
    trig = pd.read_sas(CDC_P_TRIGLY_URL, format="xport")[["SEQN", "WTSAFPRP"]]

    survey_df = demo.merge(trig, on="SEQN", how="left").rename(columns={"SEQN": "ID"})
    survey_df["ID"] = survey_df["ID"].astype("int64")
    survey_df["SDMVSTRA"] = survey_df["SDMVSTRA"].astype("int64")
    survey_df["SDMVPSU"] = survey_df["SDMVPSU"].astype("int64")

    cache_path.parent.mkdir(parents=True, exist_ok=True)
    survey_df.to_parquet(cache_path, index=False)
    print(f"Cached survey design weights to {cache_path}")
    return survey_df


def load_and_clean_matrix(csv_path: Path) -> pd.DataFrame:
    """Load the curated NHANES matrix, clean spurious columns, and attach survey weights."""
    if not csv_path.exists():
        alt_path = csv_path.parent / "nhanes_phenotype_analytical_matrix.csv"
        if alt_path.exists():
            csv_path = alt_path
        else:
            raise FileNotFoundError(
                f"Curated dataset not found at {csv_path} or {alt_path}. "
                "Place the CSV generated by data_curation_pipeline.R inside data/."
            )

    df = pd.read_csv(csv_path)

    # Drop any spurious unnamed indicator columns if present
    unnamed_cols = [c for c in df.columns if c.startswith("Unnamed:")]
    if unnamed_cols:
        df = df.drop(columns=unnamed_cols)

    # Clean non-informative survey responses in Education_Level for downstream testing
    if "Education_Level" in df.columns:
        df["Education_Level"] = df["Education_Level"].replace(
            {"Don't Know": np.nan, "Refused": np.nan}
        )

    # Attach NHANES survey design variables if not already present in the CSV
    missing_survey_cols = [c for c in SURVEY_DESIGN_COLS if c not in df.columns]
    if missing_survey_cols:
        survey_df = load_survey_design_weights(SURVEY_CACHE_PATH)
        df = df.merge(survey_df[["ID"] + missing_survey_cols], on="ID", how="left")

    return df


def filter_analytical_cohort(df: pd.DataFrame) -> pd.DataFrame:
    """Restrict to adults >= 20 years with complete fasting panel across the 6 biomarkers."""
    n_total = len(df)
    adults = df[df["Age_Years"] >= 20].copy()
    n_adults = len(adults)

    cohort = adults.dropna(subset=BIOMARKERS).reset_index(drop=True)
    n_final = len(cohort)

    print(f"Total NHANES participants loaded:          {n_total:,}")
    print(f"Adults aged >= 20 years:                   {n_adults:,}")
    print(f"Complete-case 6-biomarker cohort (N):      {n_final:,}")

    assert n_final == 3515, f"Expected N=3,515 complete cases, got {n_final}"
    return cohort


def partition_and_scale(cohort: pd.DataFrame) -> None:
    """Perform stratified 70/30 split by age decile and fit StandardScaler on train only."""
    ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)

    # Create age deciles for stratification
    age_deciles = pd.qcut(cohort["Age_Years"], q=10, duplicates="drop")

    train_df, test_df = train_test_split(
        cohort,
        test_size=TEST_SIZE,
        random_state=RANDOM_SEED,
        stratify=age_deciles,
    )

    train_df = train_df.reset_index(drop=True)
    test_df = test_df.reset_index(drop=True)

    print(f"Training split (70%):                      {len(train_df):,}")
    print(f"Held-out test split (30%):                 {len(test_df):,}")

    # Fit Z-score scaler exclusively on training set to prevent data leakage
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(train_df[BIOMARKERS])
    X_test_scaled = scaler.transform(test_df[BIOMARKERS])

    train_scaled_df = pd.DataFrame(X_train_scaled, columns=BIOMARKERS)
    train_scaled_df.insert(0, "ID", train_df["ID"].values)

    test_scaled_df = pd.DataFrame(X_test_scaled, columns=BIOMARKERS)
    test_scaled_df.insert(0, "ID", test_df["ID"].values)

    # Save partitioned datasets (stored under artifacts/, which is git-ignored)
    train_df.to_parquet(ARTIFACTS_DIR / "train_raw.parquet", index=False)
    test_df.to_parquet(ARTIFACTS_DIR / "test_raw.parquet", index=False)
    train_scaled_df.to_parquet(ARTIFACTS_DIR / "train_scaled.parquet", index=False)
    test_scaled_df.to_parquet(ARTIFACTS_DIR / "test_scaled.parquet", index=False)

    # Persist fitted scaler and split manifest
    joblib.dump(scaler, ARTIFACTS_DIR / "biomarker_scaler.joblib")

    manifest = {
        "random_seed": RANDOM_SEED,
        "test_size": TEST_SIZE,
        "n_total_cohort": int(len(cohort)),
        "n_train": int(len(train_df)),
        "n_test": int(len(test_df)),
        "biomarkers": BIOMARKERS,
        "sociodemographics": SOCIODEMOGRAPHICS,
        "secondary_clinical": SECONDARY_CLINICAL,
        "survey_design_cols": SURVEY_DESIGN_COLS,
        "train_means": dict(zip(BIOMARKERS, scaler.mean_.round(4).tolist())),
        "train_stds": dict(zip(BIOMARKERS, scaler.scale_.round(4).tolist())),
        "secondary_missingness_full_cohort": cohort[SECONDARY_CLINICAL]
        .isna()
        .sum()
        .to_dict(),
        "survey_weight_missingness_cohort": cohort[SURVEY_DESIGN_COLS]
        .isna()
        .sum()
        .to_dict(),
    }

    with open(ARTIFACTS_DIR / "split_manifest.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print(f"\nSaved prepared splits, scaler, and manifest to {ARTIFACTS_DIR}/")


def main() -> None:
    df = load_and_clean_matrix(RAW_CSV_PATH)
    cohort = filter_analytical_cohort(df)
    partition_and_scale(cohort)


if __name__ == "__main__":
    main()
